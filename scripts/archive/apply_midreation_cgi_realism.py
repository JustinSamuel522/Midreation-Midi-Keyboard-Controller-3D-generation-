def validate_source(cpp, html):
    """Compile/check candidate source in isolation; never replace files on failure."""
    cxx = shutil.which('c++') or shutil.which('clang++') or shutil.which('g++')
    node = shutil.which('node')
    with tempfile.TemporaryDirectory(prefix='midreation-cgi-validate-') as tmp:
        folder=Path(tmp)
        if cxx:
            cpp_file=folder/'candidate.cpp'
            cpp_file.write_text(cpp,encoding='utf8')
            result=subprocess.run([cxx,'-std=c++17','-fsyntax-only',str(cpp_file)],
                                  capture_output=True,text=True,timeout=90)
            if result.returncode:
                raise ValueError('Generated C++ failed syntax check:\n'+result.stderr[-5500:])
            print('C++17 syntax check passed.')
        else:
            print('No C++ compiler on PATH; skipping preflight syntax check.')
        if node:
            match=re.search(r'<script(?:\s[^>]*)?>(.*?)</script>',html,re.S|re.I)
            if not match:
                raise ValueError('Could not identify the studio inline JavaScript.')
            js_file=folder/'candidate.js'
            js_file.write_text(match.group(1),encoding='utf8')
            result=subprocess.run([node,'--check',str(js_file)],
                                  capture_output=True,text=True,timeout=25)
            if result.returncode:
                raise ValueError('Generated JavaScript failed syntax check:\n'+result.stderr[-5500:])
            print('JavaScript syntax check passed.')
        else:
            print('Node.js not on PATH; skipping JavaScript preflight syntax check.')


def main():
    try:
        if not CPP.is_file() or not HTML.is_file():
            raise ValueError('Run this from the repository root: src/main.cpp and studio/index.html must exist.')
        before_cpp=CPP.read_text(encoding='utf8')
        before_html=HTML.read_text(encoding='utf8')
        for file in (TEST, EXAMPLE):
            if file.exists():
                raise ValueError(f'{file} already exists. No existing files will be overwritten.')
        after_cpp=upgrade_cpp(before_cpp)
        after_html=upgrade_html(before_html)
        validate_source(after_cpp,after_html)
        # Require C++ / JS source to be complete and preserve existing contents.
        if len(after_cpp)<len(before_cpp) or len(after_html)<len(before_html)-4000:
            raise ValueError('Suspicious source size; refusing to modify files.')
        backup=ROOT/'build'/'cgi_realism_backup'
        if backup.exists():
            raise ValueError(f'Backup directory already exists: {backup}')
        backup.mkdir(parents=True,exist_ok=False)
        shutil.copy2(CPP,backup/'main.cpp')
        shutil.copy2(HTML,backup/'index.html')
        try:
            # Write complete files to temporary siblings, then atomically replace.
            tmp_cpp=CPP.with_name(CPP.name+'.midreation-tmp')
            tmp_html=HTML.with_name(HTML.name+'.midreation-tmp')
            tmp_cpp.write_text(after_cpp,encoding='utf8')
            tmp_html.write_text(after_html,encoding='utf8')
            os.replace(tmp_cpp,CPP)
            os.replace(tmp_html,HTML)
            TEST.parent.mkdir(parents=True,exist_ok=True)
            EXAMPLE.parent.mkdir(parents=True,exist_ok=True)
            TEST.write_text(TEST_TEXT,encoding='utf8')
            EXAMPLE.write_text(EXAMPLE_TEXT,encoding='utf8')
        except Exception:
            shutil.copy2(backup/'main.cpp',CPP)
            shutil.copy2(backup/'index.html',HTML)
            for file in (TEST, EXAMPLE, CPP.with_name(CPP.name+'.midreation-tmp'),
                         HTML.with_name(HTML.name+'.midreation-tmp')):
                if file.exists(): file.unlink()
            raise
        print('Midreation CGI Realism V2 applied (C++ + WebGL only).')
        print('Updated: src/main.cpp, studio/index.html')
        print('Created: test/test_cgi_realism.py, examples/cgi-realism-showcase.board')
        print('Backups: build/cgi_realism_backup/ (ignored by Git)')
        print('Next: cmake -S . -B build && cmake --build build')
        print("      python3 -m unittest discover -s test -p 'test_*.py' -v")
        print('      python3 studio_server.py')
        return 0
    except (ValueError,RuntimeError,OSError,AssertionError,subprocess.TimeoutExpired) as error:
        print(f'No changes applied: {error}',file=sys.stderr)
        return 1


if __name__=='__main__':
    sys.exit(main())
