# The WebGL shader uses roughness and metallic parameters; micro-detail is
# deterministic world-space so it doesn't flicker when the camera moves.
SHADERS = r'''// Midreation photorealism: physically motivated metal/plastic/glass response.
// OBJ colors remain backwards compatible; extra material values are in comments.
const vshader=`attribute vec3 aPos; attribute vec3 aNormal; attribute vec3 aColor;
attribute vec2 aMR; uniform mat4 uMVP;
varying vec3 vColor; varying vec3 vNormal; varying vec3 vPosition;
varying vec2 vMR;
void main(){gl_Position=uMVP*vec4(aPos,1.0);vColor=aColor;
vNormal=normalize(aNormal);vPosition=aPos;vMR=aMR;}`;
const fshader=`precision highp float;
varying vec3 vColor; varying vec3 vNormal; varying vec3 vPosition;
varying vec2 vMR; uniform vec3 uEye;
uniform float uFloor;uniform vec2 uBoardSize;
const float PI=3.14159265359;
float saturate(float a){return clamp(a,0.0,1.0);}
vec3 tonemap(vec3 c){return c/(c+vec3(0.85));}
float D_GGX(float noh,float rough){
 float a=rough*rough;float a2=a*a;float d=noh*noh*(a2-1.0)+1.0;
 return a2/max(PI*d*d,0.0001);
}
float G_Schlick(float nv,float k){return nv/max(nv*(1.0-k)+k,0.0001);}
vec3 BRDF(vec3 n,vec3 v,vec3 ld,vec3 lightColor,
          vec3 base,float metal,float rough){
 vec3 h=normalize(v+ld);
 float nv=saturate(dot(n,v)), nl=saturate(dot(n,ld));
 float nh=saturate(dot(n,h)), vh=saturate(dot(v,h));
 float k=pow(rough+1.0,2.0)/8.0;
 vec3 f0=mix(vec3(0.04),base,metal);
 vec3 fresnel=f0+(vec3(1.0)-f0)*pow(1.0-vh,5.0);
 vec3 spec=D_GGX(nh,rough)*G_Schlick(nv,k)*G_Schlick(nl,k)*fresnel
           /max(4.0*nv*nl,0.0001);
 vec3 diffuse=(vec3(1.0)-fresnel)*(1.0-metal)*base/PI;
 return (diffuse+spec)*nl*lightColor;
}
void main(){
 if(uFloor>0.5){
   vec2 center=uBoardSize*0.5;
   // Rounded-box signed-distance approximation: the soft shadow follows
   // the instrument footprint rather than a circular blob at its center.
   vec2 q=abs(vPosition.xz-center)-max(vec2(20.0),uBoardSize*.5-vec2(6.0));
   float signedDistance=length(max(q,0.0))+min(max(q.x,q.y),0.0);
   float contact=1.0-smoothstep(-8.0,36.0,signedDistance);
   float ambient=exp(-max(signedDistance,0.0)*.019);
   vec3 ground=vec3(.913,.936,.963)-vec3(.21)*contact
               -vec3(.032)*ambient;
   gl_FragColor=vec4(clamp(ground,0.0,1.0),1.0);return;
 }
 vec3 n=normalize(vNormal);
 vec3 v=normalize(uEye-vPosition);
 if(dot(n,v)<0.0)n=-n;
 // sRGB OBJ vertex colors to approximate linear values before shading.
 vec3 base=pow(clamp(vColor,0.001,1.0),vec3(2.2));
 float metallic=clamp(vMR.x,0.0,1.0);
 float roughness=clamp(vMR.y,0.085,0.96);
 // Tiny brushed anisotropic variation, visible primarily on metallic panels.
 float grain=sin(vPosition.x*2.73+vPosition.z*.21)*
             sin(vPosition.x*7.89+vPosition.z*.13);
 roughness=clamp(roughness+grain*.013*metallic,.085,.96);
 vec3 key=normalize(vec3(-.55,.85,.54));
 vec3 fill=normalize(vec3(.76,.57,-.35));
 vec3 rim=normalize(vec3(.11,.51,-.85));
 vec3 lit=base*(.29*(1.0-metallic)+.055);
 lit+=BRDF(n,v,key,vec3(2.2,2.08,1.96),base,metallic,roughness);
 lit+=BRDF(n,v,fill,vec3(.65,.77,1.12),base,metallic,roughness);
 lit+=BRDF(n,v,rim,vec3(.52,.62,.75),base,metallic,roughness);
 float fres=pow(1.0-saturate(dot(n,v)),5.0);
 lit+=vec3(.11,.14,.19)*fres*(.35+.65*metallic);
 // Gentle filmed highlight rolloff, not a uniformly shiny plastic look.
 gl_FragColor=vec4(pow(clamp(tonemap(lit),0.0,1.0),vec3(1.0/2.2)),1.0);
}`;
'''


def install_base_cpp(src):
    if MARKER in src:
        raise ValueError('Photorealism upgrade is already present; refusing to apply twice.')
    if 'MIDREATION_RECESSED_KEYBED_V2' not in src:
        raise ValueError('Please apply the recessed-keybed upgrade first; this patch preserves its geometry.')
    src = once(src,
               'struct Vertex {Vec3 p,n,c;};',
               'struct Vertex {Vec3 p,n,c; double metal=0.08, roughness=0.42;};',
               'material attributes')
    src = once(src,
               'vector<Vertex> vertices;int faceCount=0;double angle=0;',
               'vector<Vertex> vertices;int faceCount=0;double angle=0;\n'
               '  double currentMetal=.12,currentRoughness=.36;',
               'per-surface material state')
    src = once(src,
               'for(auto p:{a,b,c})vertices.push_back({p,n,rgb});',
               'for(auto p:{a,b,c})vertices.push_back({p,n,rgb,currentMetal,currentRoughness});',
               'material propagation to triangles')
    src = once(src,
               'vector<Vec3> outline(double x,double z,double w,double d,double r,double y,int steps=6)',
               'vector<Vec3> outline(double x,double z,double w,double d,double r,double y,int steps=10)',
               'rounder bevel tessellation')
    src = once(src,'  void build(const Layout &l){',DETAILS+'  void build(const Layout &l){', 'hardware detail builder')
    src = once_re(src,
       r'(\n\s+if\(p\.type=="body"\)\{\n\s+renderChassis\(l,p,c,deck\);)',
       lambda m:m.group(1)+'\n        photorealDetails(l,p,deck);',
       'detail invocation')
    src = once(src,
               'double cx=x+w*.5,cz=z+d*.5;\n      if(p.type=="body"){',
               '''double cx=x+w*.5,cz=z+d*.5;
      // Keep per-object material identity through OBJ export. These values
      // are not guessed from color: metal/rubber/ivory have different surfaces.
      currentMetal=.10;currentRoughness=.38;
      if(p.type=="body") {currentMetal=.54;currentRoughness=.28;}
      else if(p.type=="white_key") {currentMetal=.01;currentRoughness=.24;}
      else if(p.type=="black_key") {currentMetal=.01;currentRoughness=.36;}
      else if(p.type=="knob" || p.type=="switch" || p.type=="footswitch")
        {currentMetal=.77;currentRoughness=.24;}
      else if(p.type=="fader" || p.type=="port")
        {currentMetal=.63;currentRoughness=.30;}
      else if(p.type=="pad") {currentMetal=.005;currentRoughness=.71;}
      else if(p.type=="display" || p.type=="xypad")
        {currentMetal=.04;currentRoughness=.12;}
      else if(p.type=="button" || p.type=="clicky" || p.type=="wheel")
        {currentMetal=.025;currentRoughness=.40;}
      if(p.type=="body"){''',
               'per-part material selection')
    # Keep standard 6-component vertex colors in the OBJ. The #mr extension
    # follows an ordinary OBJ comment, so other software can ignore it safely.
    old="o<<\"v \"<<v.p.x<<' '<<yy<<' '<<zz<<' '<<v.c.x<<' '<<v.c.y<<' '<<v.c.z<<'\\n';"
    new="o<<\"v \"<<v.p.x<<' '<<yy<<' '<<zz<<' '<<v.c.x<<' '<<v.c.y<<' '<<v.c.z<<\" #mr \"<<v.metal<<' '<<v.roughness<<'\\n';"
    src = once(src,old,new,'material metadata in exported OBJ')
    return src


