def upgrade_cpp(src):
    if CGI_MARKER in src:
        raise ValueError('CGI Realism V2 has already been applied; no changes made.')
    if 'MIDREATION_RECESSED_KEYBED_V2' not in src:
        raise ValueError('Apply the recessed-keybed update first; the CGI upgrade must not flatten your keyboard.')
    # Previous photoreal materials update is optional. The entire renderer
    # remains CGI, inside the existing C++ geometry engine and WebGL preview.
    if MARKER not in src:
        src = install_base_cpp(src)

    src = once(src, 'double width=0,depth=0,tilt=0;',
               'double width=0,depth=0,tilt=0,caseRadius=12.5,keybedOverhang=15.5;',
               'procedural geometry controls')
    src = once(src,
               's.panels=get(a,"panels",get(a,"corners",s.panels));s.tilt=getDouble(a,"tilt",s.tilt);',
               's.panels=get(a,"panels",get(a,"corners",s.panels));s.tilt=getDouble(a,"tilt",s.tilt);\n'
               '        s.caseRadius=getDouble(a,"corner_radius",s.caseRadius);\n'
               '        s.keybedOverhang=getDouble(a,"keybed_overhang",s.keybedOverhang);',
               'new STYLE geometry grammar')
    src = once(src,
               'if(s.tilt<-20||s.tilt>25)throw runtime_error("Tilt must be from -20 to 25 degrees");',
               'if(s.tilt<-20||s.tilt>25)throw runtime_error("Tilt must be from -20 to 25 degrees");\n'
               '  if(s.caseRadius<2||s.caseRadius>25)throw runtime_error("corner_radius must be 2..25 mm");\n'
               '  if(s.keybedOverhang<6||s.keybedOverhang>23)throw runtime_error("keybed_overhang must be 6..23 mm");',
               'grammar parameter validation')
    src = once(src,'roundedPrism(x,0,z,w,max(4.,deck-3.9),d,12.5,3.8,shade(c,.77));',
               'roundedPrism(x,0,z,w,max(4.,deck-3.9),d,l.spec.caseRadius,3.8,shade(c,.77));',
               'board corner radius')
    src = once(src,'roundedPrism(x,0,z,w,lowShellTop,d,12.5,2.6,shade(c,.74));',
               'roundedPrism(x,0,z,w,lowShellTop,d,l.spec.caseRadius,2.6,shade(c,.74));',
               'keyboard corner radius')
    src = once(src,'roundedPrism(keyLeft-7.0,deck-4.2,keyBack-7.5,keyW+14.0,4.2,23.0,',
               'roundedPrism(keyLeft-7.0,deck-4.2,keyBack-7.5,keyW+14.0,4.2,\n'
               '                   7.5+l.spec.keybedOverhang,',
               'variable rear overhang')
    src = once(src,'  void build(const Layout &l){',CGI_GEOMETRY+'  void build(const Layout &l){',
               'procedural manufactured details')
    src = once(src,'        renderChassis(l,p,c,deck);',
               '        renderChassis(l,p,c,deck);\n        cgiHousingDetails(l,p,deck);',
               'raised-chassis detail placement')
    src = once(src,'      ++index;\n    }\n  }\n  void obj(',
               '      cgiControlDetails(p,deck,keyProfile);\n      ++index;\n    }\n  }\n  void obj(',
               'per-component highlight details')
    src = once(src,'o<<",\\"triangles\\":"<<mesh.faceCount<<",\\"parts\\":[";',
               'o<<",\\"cgi\\":{\\"cornerRadius\\":"<<l.spec.caseRadius\n'
               '   <<",\\"keybedOverhang\\":"<<l.spec.keybedOverhang<<"}";\n'
               '  o<<",\\"triangles\\":"<<mesh.faceCount<<",\\"parts\\":[";',
               'expose controlled shape parameters in JSON')
    # Add the red finish if the visual upgrade wasn't previously applied.
    if '{"bright-red",' not in src:
        src = once(src, '{"red",{.90,.26,.32}},',
                   '{"red",{.90,.26,.32}},{"bright-red",{.96,.075,.11}},',
                   'bright-red CGI material')
    return src


def upgrade_html(src):
    if CGI_MARKER in src:
        raise ValueError('The WebGL CGI upgrade is already applied.')
    if 'aMR' not in src:
        src = install_base_html(src)
    # Every procedural vertex is now 11 floats: position(3), normal(3),
    # color(3), metallic(1), roughness(1). Old 9-float count is a subtle bug.
    if 'vertexCount=output.length/9;' in src:
        src = once(src,'vertexCount=output.length/9;',
                   'vertexCount=output.length/11;', 'material-aware vertex count')
    elif 'vertexCount=output.length/11;' not in src:
        raise ValueError('Unexpected WebGL vertex layout; refusing to modify.')
    src = once(src,'const vshader=`',
               '// MIDREATION_CGI_REALISM_V2 — procedural real-time CGI materials\nconst vshader=`',
               'CGI shader marker')
    if "{name:'Bright red',value:'bright-red'" not in src:
        src = once(src,
                   "{name:'Midnight black',value:'black',hex:'#11131b'},",
                   "{name:'Midnight black',value:'black',hex:'#11131b'},"
                   "{name:'Bright red',value:'bright-red',hex:'#f5131c'},",
                   'red finish swatch')
    # Target the raised panel, not the underside of the keyboard case.
    if 'const target=[this.width/2,5,this.depth/2]' in src:
        src = once(src,'const target=[this.width/2,5,this.depth/2]',
                   'const target=[this.width/2,19,this.depth/2]',
                   'studio camera target')
    marker='The friendly builder writes this specification automatically. For class demonstrations, you can edit it directly.'
    if marker in src:
        src = once(src,marker,
                   marker+' Optional shape parameters: STYLE corner_radius=12.5 keybed_overhang=15.5.',
                   'grammar customization hint')
    return src


