def once(text, old, new, label):
    n = text.count(old)
    if n != 1:
        raise ValueError(f'{label}: expected one source match, found {n}; no files were changed')
    return text.replace(old, new, 1)


def once_re(text, pat, new, label, flags=0):
    text, n = re.subn(pat, lambda m: new(m) if callable(new) else new, text, flags=flags)
    if n != 1:
        raise ValueError(f'{label}: expected one source match, found {n}; no files were changed')
    return text


